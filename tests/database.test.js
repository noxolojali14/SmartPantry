import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { describe, it } from "node:test";
import { createSupabaseClient, verifySupabaseConnection } from "../src/database/db.js";
import { createFakeSupabase } from "./support/fakeSupabase.js";

const schema = readFileSync(new URL("../supabase/schema.sql", import.meta.url), "utf8");

describe("Supabase database setup", () => {
  it("creates all tables in dependency order with PostgreSQL types", () => {
    const tableNames = ["users", "sessions", "pantry_items", "shopping_list_items", "meals", "meal_ingredients"];
    const positions = tableNames.map((name) => schema.indexOf(`create table if not exists public.${name}`));
    assert.ok(positions.every((position) => position >= 0));
    assert.deepEqual(positions, [...positions].sort((left, right) => left - right));
    assert.match(schema, /bigint generated by default as identity/);
    assert.match(schema, /timestamptz not null default now\(\)/);
    assert.match(schema, /foreign key \(meal_id, user_id\) references public\.meals\(id, user_id\) on delete cascade/);
    assert.doesNotMatch(schema, /collate nocase|datetime\(['"]now['"]\)|integer primary key autoincrement/i);
  });

  it("includes case-insensitive email uniqueness, RLS, and transactional meal functions", () => {
    assert.match(schema, /unique index if not exists users_email_lower_uidx on public\.users \(lower\(email\)\)/i);
    for (const table of ["users", "sessions", "pantry_items", "shopping_list_items", "meals", "meal_ingredients"]) {
      assert.match(schema, new RegExp(`alter table public\\.${table} enable row level security`, "i"));
    }
    assert.match(schema, /create or replace function public\.create_meal_with_ingredients/i);
    assert.match(schema, /create or replace function public\.update_meal_with_ingredients/i);
    assert.match(schema, /revoke all on function public\.create_meal_with_ingredients/i);
    assert.match(schema, /grant execute on function public\.create_meal_with_ingredients[^;]+to service_role/i);
  });

  it("upgrades existing sessions expiry columns before indexing expires_at", () => {
    const migrationPosition = schema.indexOf("information_schema.columns");
    const expiryIndexPosition = schema.indexOf("sessions_expires_at_idx");
    assert.ok(migrationPosition >= 0);
    assert.ok(expiryIndexPosition > migrationPosition);
    assert.match(schema, /rename column expires to expires_at/i);
    assert.match(schema, /to_timestamp\(/i);
    assert.match(schema, /alter table public\.sessions drop column expires/i);
  });

  it("requires valid server-side connection settings and builds the official Supabase client", () => {
    assert.throws(() => createSupabaseClient({ url: "", serviceRoleKey: "" }), /must be configured/);
    assert.throws(() => createSupabaseClient({ url: "not-a-url", serviceRoleKey: "test" }), /valid URL/);
    assert.throws(() => createSupabaseClient({ url: "http://example.com", serviceRoleKey: "test" }), /must use HTTPS/);
    const client = createSupabaseClient({ url: "https://project.supabase.co", serviceRoleKey: "test-service-key" });
    assert.equal(typeof client.from, "function");
    assert.equal(typeof client.rpc, "function");
  });

  it("verifies database connectivity and explains when the project schema is missing", async () => {
    await verifySupabaseConnection(createFakeSupabase());
    const missingTableClient = createFakeSupabase();
    delete missingTableClient.tables.users;
    await assert.rejects(verifySupabaseConnection(missingTableClient), /public\.users is missing/);
  });
});