-- SmartPantry PostgreSQL schema for Supabase.
-- The Express server uses the server-only service_role key. Do not expose it in the browser.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  email text not null check (char_length(email) between 3 and 254),
  password_hash text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists users_email_lower_uidx on public.users (lower(email));

create table if not exists public.sessions (
  sid text primary key,
  sess jsonb not null,
  expires_at timestamptz not null
);

-- Upgrade sessions created by earlier schema attempts. Expiry values written by the
-- previous store were epoch milliseconds; timestamp and text variants are handled too.
do $$
declare
  v_sess_type text;
  v_expiry_type text;
begin
  select data_type into v_sess_type
  from information_schema.columns
  where table_schema = 'public' and table_name = 'sessions' and column_name = 'sess';

  if v_sess_type is null then
    raise exception 'public.sessions is missing the sess column';
  elsif v_sess_type <> 'jsonb' then
    execute 'alter table public.sessions alter column sess type jsonb using sess::jsonb';
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sessions' and column_name = 'expires_at'
  ) then
    select data_type into v_expiry_type
    from information_schema.columns
    where table_schema = 'public' and table_name = 'sessions' and column_name = 'expires';

    if v_expiry_type in ('smallint', 'integer', 'bigint', 'numeric', 'real', 'double precision') then
      alter table public.sessions add column expires_at timestamptz;
      execute $migration$
        update public.sessions
        set expires_at = pg_catalog.to_timestamp((
          case when expires::numeric > 99999999999 then expires::numeric / 1000 else expires::numeric end
        )::double precision)
        where expires_at is null
      $migration$;
      alter table public.sessions drop column expires;
    elsif v_expiry_type = 'timestamp with time zone' then
      alter table public.sessions rename column expires to expires_at;
    elsif v_expiry_type = 'timestamp without time zone' then
      alter table public.sessions rename column expires to expires_at;
      alter table public.sessions alter column expires_at type timestamptz
        using expires_at at time zone 'UTC';
    elsif v_expiry_type = 'text' then
      alter table public.sessions add column expires_at timestamptz;
      execute $migration$
        update public.sessions
        set expires_at = case
          when btrim(expires) ~ '^-?[0-9]+([.][0-9]+)?$' then pg_catalog.to_timestamp((
            case when btrim(expires)::numeric > 99999999999 then btrim(expires)::numeric / 1000
                 else btrim(expires)::numeric end
          )::double precision)
          else btrim(expires)::timestamptz
        end
        where expires_at is null and expires is not null
      $migration$;
      alter table public.sessions drop column expires;
    elsif v_expiry_type is null then
      alter table public.sessions add column expires_at timestamptz;
      update public.sessions set expires_at = now() where expires_at is null;
    else
      raise exception 'Unsupported public.sessions.expires type: %', v_expiry_type;
    end if;
  end if;

  update public.sessions set expires_at = now() where expires_at is null;
  alter table public.sessions alter column expires_at set default now();
  alter table public.sessions alter column expires_at set not null;
end;
$$;

create index if not exists sessions_expires_at_idx on public.sessions (expires_at);

create table if not exists public.pantry_items (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  quantity numeric(12, 3) not null check (quantity > 0 and quantity <> 'NaN'::numeric),
  unit text not null default '' check (char_length(unit) <= 30),
  category text not null default '' check (char_length(category) <= 50),
  expiry_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists pantry_items_user_idx on public.pantry_items (user_id);
create index if not exists pantry_items_user_expiry_idx on public.pantry_items (user_id, expiry_date) where expiry_date is not null;

create table if not exists public.shopping_list_items (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  quantity numeric(12, 3) not null check (quantity > 0 and quantity <> 'NaN'::numeric),
  unit text not null default '' check (char_length(unit) <= 30),
  is_purchased boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists shopping_list_items_user_idx on public.shopping_list_items (user_id);
create index if not exists shopping_list_items_user_purchased_idx on public.shopping_list_items (user_id, is_purchased);

create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  instructions text not null default '' check (char_length(instructions) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create index if not exists meals_user_idx on public.meals (user_id);

create table if not exists public.meal_ingredients (
  id bigint generated by default as identity primary key,
  meal_id bigint not null,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  quantity numeric(12, 3) check (quantity is null or (quantity > 0 and quantity <> 'NaN'::numeric)),
  unit text not null default '' check (char_length(unit) <= 30),
  created_at timestamptz not null default now(),
  foreign key (meal_id, user_id) references public.meals(id, user_id) on delete cascade
);

create index if not exists meal_ingredients_meal_user_idx on public.meal_ingredients (meal_id, user_id);

alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.pantry_items enable row level security;
alter table public.shopping_list_items enable row level security;
alter table public.meals enable row level security;
alter table public.meal_ingredients enable row level security;

-- There are intentionally no anon/authenticated table policies. The server-side service_role client
-- bypasses RLS; every API query must still filter by the authenticated user's id.
grant all privileges on table public.users, public.sessions, public.pantry_items,
  public.shopping_list_items, public.meals, public.meal_ingredients to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

drop trigger if exists pantry_items_set_updated_at on public.pantry_items;
create trigger pantry_items_set_updated_at before update on public.pantry_items
  for each row execute function public.set_updated_at();
drop trigger if exists shopping_list_items_set_updated_at on public.shopping_list_items;
create trigger shopping_list_items_set_updated_at before update on public.shopping_list_items
  for each row execute function public.set_updated_at();
drop trigger if exists meals_set_updated_at on public.meals;
create trigger meals_set_updated_at before update on public.meals
  for each row execute function public.set_updated_at();

create or replace function public.create_meal_with_ingredients(
  p_user_id bigint,
  p_name text,
  p_instructions text,
  p_ingredients jsonb
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_meal_id bigint;
  v_ingredient jsonb;
begin
  insert into public.meals (user_id, name, instructions)
  values (p_user_id, p_name, coalesce(p_instructions, ''))
  returning id into v_meal_id;

  for v_ingredient in
    select value from pg_catalog.jsonb_array_elements(coalesce(p_ingredients, '[]'::jsonb)) as ingredients(value)
  loop
    insert into public.meal_ingredients (meal_id, user_id, name, quantity, unit)
    values (
      v_meal_id,
      p_user_id,
      v_ingredient ->> 'name',
      nullif(v_ingredient ->> 'quantity', '')::numeric,
      coalesce(v_ingredient ->> 'unit', '')
    );
  end loop;

  return v_meal_id;
end;
$$;

create or replace function public.update_meal_with_ingredients(
  p_user_id bigint,
  p_meal_id bigint,
  p_fields jsonb,
  p_replace_ingredients boolean,
  p_ingredients jsonb
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_meal_id bigint;
  v_ingredient jsonb;
begin
  update public.meals
  set name = case when p_fields ? 'name' then p_fields ->> 'name' else name end,
      instructions = case when p_fields ? 'instructions' then p_fields ->> 'instructions' else instructions end
  where id = p_meal_id and user_id = p_user_id
  returning id into v_meal_id;

  if v_meal_id is null then
    raise exception 'meal_not_found' using errcode = 'P0002';
  end if;

  if p_replace_ingredients then
    delete from public.meal_ingredients where meal_id = v_meal_id and user_id = p_user_id;
    for v_ingredient in
      select value from pg_catalog.jsonb_array_elements(coalesce(p_ingredients, '[]'::jsonb)) as ingredients(value)
    loop
      insert into public.meal_ingredients (meal_id, user_id, name, quantity, unit)
      values (
        v_meal_id,
        p_user_id,
        v_ingredient ->> 'name',
        nullif(v_ingredient ->> 'quantity', '')::numeric,
        coalesce(v_ingredient ->> 'unit', '')
      );
    end loop;
  end if;

  return v_meal_id;
end;
$$;

revoke all on function public.create_meal_with_ingredients(bigint, text, text, jsonb) from public, anon, authenticated;
revoke all on function public.update_meal_with_ingredients(bigint, bigint, jsonb, boolean, jsonb) from public, anon, authenticated;
grant execute on function public.create_meal_with_ingredients(bigint, text, text, jsonb) to service_role;
grant execute on function public.update_meal_with_ingredients(bigint, bigint, jsonb, boolean, jsonb) to service_role;